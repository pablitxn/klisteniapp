import { expect, test } from '@playwright/test'
import { createDefaultPersonalData } from '@klisteniapp/scene-schema'
import { openSettings } from './settings-helpers'

test.beforeEach(async ({ page }) => { await page.route('**/models/*.glb', route => route.abort()) })

test('settings keeps appearance, privacy and data in one accessible dialog on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  const dialog = await openSettings(page)
  await expect(dialog.getByRole('combobox', { name: 'Idioma', exact: true })).toBeVisible()
  await expect(dialog.getByRole('combobox', { name: 'Modo', exact: true })).toBeVisible()
  await expect(dialog.getByRole('button', { name: 'Cuenta y planificación', exact: true })).toHaveCount(0)
  await openSettings(page, 'Privacidad')
  await expect(page.getByTestId('privacy-dialog')).toBeVisible()
  await expect(page.locator('dialog:visible')).toHaveCount(1)
  await expect(dialog.getByTestId('privacy-policy')).toBeVisible()
  await openSettings(page, 'Datos')
  await expect(dialog.getByRole('button', { name: 'Exportar mis datos', exact: true })).toBeVisible()
  await expect(dialog.getByRole('button', { name: 'Importar una copia', exact: true })).toBeVisible()
  await expect(dialog.getByRole('combobox', { name: 'Idioma', exact: true })).toBeHidden()
  await expect(page.locator('dialog:visible')).toHaveCount(1)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await dialog.getByRole('button', { name: 'Cerrar', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Abrir ajustes', exact: true })).toBeFocused()
})

test('initial setup retains unsaved fields through the privacy policy round trip', async ({ page }) => {
  await page.goto('/')
  const dialog = await openSettings(page, 'Configuración inicial')
  await dialog.getByRole('button', { name: 'Comenzar configuración', exact: true }).click()
  await dialog.getByLabel('Altura (cm)', { exact: true }).fill('180')
  await dialog.getByLabel('Mi contexto', { exact: true }).fill('An unsaved private setup draft')
  await openSettings(page, 'Privacidad')
  await expect(page.locator('dialog:visible')).toHaveCount(1)
  await dialog.getByTestId('privacy-policy').click()
  await expect(page.getByRole('heading', { name: 'Tu práctica, bajo tu control.', exact: true })).toBeVisible()
  await expect(page.locator('dialog:visible')).toHaveCount(0)
  await page.getByRole('link', { name: '← Volver a Klisteni', exact: true }).click()
  await expect(dialog).toBeVisible()
  await openSettings(page, 'Configuración inicial')
  await expect(dialog.getByLabel('Altura (cm)', { exact: true })).toHaveValue('180')
  await expect(dialog.getByLabel('Mi contexto', { exact: true })).toHaveValue('An unsaved private setup draft')
  await expect(page.locator('dialog:visible')).toHaveCount(1)
  expect(await page.evaluate(() => localStorage.getItem('klisteniapp.personal.v2'))).toBeNull()
})

test('initial setup appends a measurement and can be replayed without deleting saved practice or health', async ({ page }) => {
  const data = createDefaultPersonalData('Existing local practice', 'UTC')
  data.settings.health!.profile = { heightCm: 178, context: 'Keep this private context' }
  data.settings.health!.measurements = [{ id: 'existing-measurement', date: '2026-09-28', recordedAt: '2026-09-28T12:00:00Z', source: { kind: 'manual' }, weightKg: 80 }]
  data.settings.health!.goals = [{ id: 'existing-goal', title: 'Keep this goal', metric: 'weeklyTrainingDays', target: 3, startDate: '2026-09-28' }]
  data.progress.workouts = [{ id: 'existing-workout', date: '2026-09-28', completedAt: '2026-09-28T12:00:00Z', exercises: [{ exerciseId: 'pushup', sets: 2, reps: 8 }], durationMinutes: 12 }]
  data.progress.cardio = [{ id: 'existing-walk', date: '2026-09-29', activity: 'walk', minutes: 20 }]
  await page.addInitScript(value => {
    if (sessionStorage.getItem('settings-test-seeded')) return
    localStorage.setItem('klisteniapp.personal.v2', JSON.stringify(value))
    localStorage.setItem('klisteniapp.progress.v1', JSON.stringify(value.progress))
    sessionStorage.setItem('settings-test-seeded', '1')
  }, data)
  await page.goto('/')
  const dialog = await openSettings(page, 'Configuración inicial')
  await expect(dialog.getByRole('heading', { name: 'Configuración inicial', exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: 'Comenzar configuración', exact: true }).click()
  await expect(dialog.getByLabel('Altura (cm)', { exact: true })).toHaveValue('178')
  await dialog.getByLabel('Altura (cm)', { exact: true }).fill('179')
  await dialog.getByRole('button', { name: 'Guardar y continuar', exact: true }).click()
  await dialog.getByLabel('Peso (kg)', { exact: true }).fill('79.5')
  await dialog.getByRole('button', { name: 'Guardar y finalizar', exact: true }).click()
  await expect(dialog.getByRole('heading', { name: 'Configuración revisada', exact: true })).toBeVisible()
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('klisteniapp.personal.v2')!))
  expect(saved.settings.health.profile).toMatchObject({ heightCm: 179, context: 'Keep this private context' })
  expect(saved.settings.health.measurements).toHaveLength(2)
  expect(saved.settings.health.measurements[0]).toEqual(data.settings.health!.measurements[0])
  expect(saved.settings.health.measurements[1]).toMatchObject({ id: expect.any(String), weightKg: 79.5, source: { kind: 'manual' } })
  expect(saved.settings.health.measurements[1].id).not.toBe('existing-measurement')
  expect(saved.settings.health.goals).toEqual(data.settings.health!.goals)
  expect(saved.progress).toEqual(data.progress)
  await dialog.getByRole('button', { name: 'Volver a empezar', exact: true }).click()
  await expect(dialog.getByLabel('Altura (cm)', { exact: true })).toHaveValue('179')
  await dialog.getByRole('button', { name: 'Continuar sin cambios', exact: true }).click()
  await expect(dialog.getByLabel('Peso (kg)', { exact: true })).toHaveValue('')
  await dialog.getByRole('button', { name: 'Seguir sin agregar una medición', exact: true }).click()
  await expect(dialog.getByRole('heading', { name: 'Configuración revisada', exact: true })).toBeVisible()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('klisteniapp.personal.v2')!))).toEqual(saved)
  await page.reload()
  const reopened = await openSettings(page, 'Configuración inicial')
  await reopened.getByRole('button', { name: 'Comenzar configuración', exact: true }).click()
  await expect(reopened.getByLabel('Altura (cm)', { exact: true })).toHaveValue('179')
  await reopened.getByRole('button', { name: 'Continuar sin cambios', exact: true }).click()
  await reopened.getByRole('button', { name: 'Seguir sin agregar una medición', exact: true }).click()
  await expect(reopened.getByRole('heading', { name: 'Configuración revisada', exact: true })).toBeVisible()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('klisteniapp.personal.v2')!))).toEqual(saved)
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('klisteniapp.progress.v1')!))).toEqual(data.progress)
})
