test('corrupt local history shows a warning instead of inventing progress', async ({ page }) => {
  await page.addInitScript(key => localStorage.setItem(key, '{broken-json'), progressKey)
  await openPage(page)
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(page.locator('.stats-bar')).toContainText('0 XP')
  expect(await page.evaluate(key => localStorage.getItem(key), progressKey)).toBe('{broken-json')
})

test('cardio saves entered minutes and distance, survives reload, exports and deletes', async ({ page }) => {
  await openPage(page)
  await page.getByRole('button', { name: 'Registrar actividad', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: 'Bici', exact: true }).click()
  await dialog.getByLabel('Duración (minutos)').fill('25')
  await dialog.getByLabel(/Distancia \(km\)/).fill('4.5')
  const date = await dialog.getByLabel('¿Cuándo?').inputValue()
  await dialog.getByRole('button', { name: 'Guardar actividad' }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.locator('.activity-history')).toContainText('Bici')
  await expect(page.locator('.activity-history')).toContainText('25 min · 4.5 km')
  await expect(page.locator('.stats-bar')).toContainText('25 XP')
  const stored = await page.evaluate(key => JSON.parse(localStorage.getItem(key)!), progressKey)
  expect(stored.workouts).toEqual([])
  expect(stored.cardio).toEqual([{ id: expect.any(String), activity: 'bike', date, minutes: 25, distanceKm: 4.5 }])
  await page.reload()
  await navigate(page, 'Mi progreso')
  await expect(page.locator('.activity-history')).toContainText('25 min · 4.5 km')
  await page.getByRole('button', { name: 'Abrir ajustes' }).click()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Exportar progreso' }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toMatch(/^klisteni-progreso-\d{4}-\d{2}-\d{2}\.json$/)
  const stream = await download.createReadStream()
  if (!stream) throw new Error('No se generó el archivo exportado')
  let exported = ''
  for await (const chunk of stream) exported += String(chunk)
  expect(JSON.parse(exported)).toEqual(stored)
  await page.getByRole('button', { name: 'Cerrar', exact: true }).click()
  await page.getByRole('button', { name: /^Eliminar Bici del/ }).click()
  await page.getByRole('button', { name: 'Cancelar', exact: true }).click()
  await expect(page.locator('.activity-history article')).toHaveCount(1)
  await page.getByRole('button', { name: /^Eliminar Bici del/ }).click()
  await page.getByRole('button', { name: 'Sí, eliminar' }).click()
  await expect(page.locator('.activity-history article')).toHaveCount(0)
  await expect(page.locator('.stats-bar')).toContainText('0 XP')
})

