test('an active session prevents restarting or editing its routine and retains its current exercise', async ({ page }) => {
  await openPage(page)
  const start = page.getByRole('button', { name: 'Empezar mi rutina' })
  const customize = page.getByRole('button', { name: 'Personalizar', exact: true })
  await start.click()
  const session = page.getByRole('region', { name: 'Sesión en curso', exact: true })
  await expect(start).toBeDisabled()
  await expect(customize).toBeDisabled()
  await session.getByRole('button', { name: 'Registrar serie' }).click()
  await page.locator('.exercise-row').filter({ hasText: 'Sentadilla' }).click()
  await expect(page.locator('.workbench-title')).toContainText('Sentadilla')
  await session.getByRole('button', { name: /Ver este movimiento/ }).click()
  await expect(page.locator('.workbench-title')).toContainText('Flexiones con rodillas')
  await expect(session).toContainText('Serie 2 de 2')
  await session.getByRole('button', { name: 'Salir de la sesión' }).click()
  await session.getByRole('button', { name: 'Salir sin guardar' }).click()
  await expect(start).toBeEnabled()
  await expect(customize).toBeEnabled()
  expect(await page.evaluate(key => localStorage.getItem(key), progressKey)).toBeNull()
})

test('saving after corrupt history retains a downloadable original and stores valid new activity', async ({ page }) => {
  const corrupt = '{broken-json-with-valuable-original-data'
  await openPage(page)
  await page.evaluate(({ key, raw }) => localStorage.setItem(key, raw), { key: progressKey, raw: corrupt })
  await page.reload()
  await expect(page.getByRole('alert')).toBeVisible()
  await page.getByRole('button', { name: 'Registrar actividad', exact: true }).click()
  await page.getByRole('dialog').getByLabel('Duración (minutos)').fill('18')
  await page.getByRole('button', { name: 'Guardar actividad' }).click()
  await expect(page.locator('.activity-history')).toContainText('Caminata')
  await expect(page.locator('.stats-bar')).toContainText('18 XP')
  await expect(page.getByRole('alert')).not.toBeVisible()
  const saved = await page.evaluate(key => ({ progress: JSON.parse(localStorage.getItem(key)!), recovery: localStorage.getItem('klisteniapp.progress.recovery') }), progressKey)
  expect(saved.recovery).toBe(corrupt)
  expect(saved.progress).toMatchObject({ version: 1, workouts: [], cardio: [{ activity: 'walk', minutes: 18 }] })
  await page.reload()
  await expect(page.locator('.stats-bar')).toContainText('18 XP')
  await page.getByRole('button', { name: 'Abrir ajustes' }).click()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Descargar original para recuperar' }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toBe('klisteni-recuperacion.txt')
  const stream = await download.createReadStream()
  if (!stream) throw new Error('No se generó la copia de recuperación')
  let exported = ''
  for await (const chunk of stream) exported += String(chunk)
  expect(exported).toBe(corrupt)
})
