test('a completed session saves exactly the twelve sets entered by the user', async ({ page }) => {
  await openPage(page)
  await page.getByRole('button', { name: 'Empezar mi rutina' }).click()
  const session = page.getByRole('region', { name: 'Sesión en curso', exact: true })
  for (let index = 0; index < 12; index++) {
    if (index > 0) await session.getByRole('button', { name: 'Omitir descanso' }).click()
    await session.getByRole('spinbutton', { name: 'Repeticiones', exact: true }).fill(String(index === 0 ? 7 : 8))
    await session.getByRole('button', { name: 'Registrar serie' }).click()
  }
  await expect(session).toContainText('12 series registradas')
  expect(await page.evaluate(key => localStorage.getItem(key), progressKey)).toBeNull()
  await session.getByRole('button', { name: 'Guardar sesión' }).click()
  await expect(session).not.toBeVisible()
  await expect(page.locator('.activity-history')).toContainText('6 ejercicios · 12 series')
  await expect(page.locator('.stats-bar')).toContainText('120 XP')
  const stored = await page.evaluate(key => JSON.parse(localStorage.getItem(key)!), progressKey)
  expect(stored.cardio).toEqual([])
  expect(stored.workouts).toHaveLength(1)
  expect(stored.workouts[0].exercises).toHaveLength(12)
  expect(stored.workouts[0].exercises[0]).toEqual({ exerciseId: 'pushup', sets: 1, reps: 7 })
  expect(stored.workouts[0].exercises.reduce((total: number, entry: { sets: number }) => total + entry.sets, 0)).toBe(12)
  await page.reload()
  await navigate(page, 'Mi progreso')
  await expect(page.locator('.activity-history article')).toHaveCount(1)
  await expect(page.locator('.stats-bar')).toContainText('120 XP')
})

