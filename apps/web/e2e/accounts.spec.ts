import { expect, test, type BrowserContext, type Page } from '@playwright/test'
import { createDefaultPersonalData, dateInTimeZone, type ServerState } from '@klisteniapp/scene-schema'
import { exercises } from '../src/data/exercises'

const password = 'Only-for-browser-tests-2026!'
const progressKey = 'klisteniapp.progress.v1'

async function prepare(context: BrowserContext, ip: number) {
  await context.setExtraHTTPHeaders({ 'X-Klisteniapp-Test-Client-IP': `198.51.100.${ip}` })
  // Rendering acceptance remains in the public WebGL suite. Exercise account UI
  // against the real API while keeping these tests independent of GPU speed.
  await context.route('**/models/*.glb', route => route.abort())
}
async function open(page: Page) {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Tu cuerpo. Tu primer gimnasio.' })).toBeVisible()
}
async function login(page: Page, name: string) {
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Entrar a Klisteni' })
  await dialog.getByLabel('Email', { exact: true }).fill(`${name.toLowerCase()}@accounts.test`)
  await dialog.getByLabel('Contraseña', { exact: true }).fill(password)
  await dialog.getByRole('button', { name: 'Entrar a mi cuenta' }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.locator('.local-badge')).toContainText('Sincronizado con tu cuenta')
}
async function accountPanel(page: Page) {
  await page.locator('.account-login').click()
  const dialog = page.getByRole('dialog', { name: 'Mi cuenta y planificación' })
  await expect(dialog).toBeVisible()
  return dialog
}
async function progress(page: Page) {
  await page.getByRole('navigation', { name: 'Navegación principal', exact: true }).getByRole('button', { name: 'Mi progreso', exact: true }).click()
}
async function readState(page: Page): Promise<ServerState> {
  return page.evaluate(async () => {
    const session = await fetch('/api/auth/get-session', { cache: 'no-store' }).then(response => response.json())
    const response = await fetch('/api/me/state', { cache: 'no-store', headers: { 'X-Klisteni-Account': session.user.id } })
    if (!response.ok) throw new Error(`Could not read state: ${response.status}`)
    return response.json()
  })
}
async function saveCardio(page: Page, minutes: number) {
  await page.getByRole('button', { name: 'Registrar actividad', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Duración (minutos)').fill(String(minutes))
  await dialog.getByRole('button', { name: 'Guardar actividad' }).click()
  await expect(dialog).not.toBeVisible()
}

test('public exploration, explicit local migration, two devices and isolated accounts', async ({ page, context, browser }) => {
  await prepare(context, 11)
  const local = { version: 1, workouts: [], cardio: [{ id: 'legacy-browser-walk', date: '2026-09-28', activity: 'walk', minutes: 17 }] }
  await page.addInitScript(({ key, data }) => localStorage.setItem(key, JSON.stringify(data)), { key: progressKey, data: local })
  await open(page)
  await expect(page.locator('.account-status')).toContainText('Modo local')
  await page.getByRole('navigation', { name: 'Navegación principal', exact: true }).getByRole('button', { name: 'Ejercicios', exact: true }).click()
  await expect(page.locator('.library-card')).toHaveCount(exercises.length)
  await login(page, 'Alice')
  expect((await readState(page)).data.progress.cardio).toEqual([])
  await progress(page)
  await expect(page.getByText('Tu primer paso todavía está por escribir.')).toBeVisible()
  const dialog = await accountPanel(page)
  await expect(dialog).toContainText('0 sesiones de fuerza y 1 actividades de cardio')
  await dialog.getByRole('button', { name: 'Incorporar mis datos locales' }).click()
  await expect(dialog).toContainText('Datos incorporados.')
  await dialog.getByRole('button', { name: 'Incorporar mis datos locales' }).click()
  await expect.poll(async () => (await readState(page)).data.progress.cardio.length).toBe(1)
  expect(await page.evaluate(key => JSON.parse(localStorage.getItem(key)!), progressKey)).toEqual(local)
  await dialog.getByRole('button', { name: 'Cerrar', exact: true }).click()
  await saveCardio(page, 23)
  await expect(page.locator('.activity-history')).toContainText('23 min')

  const otherDevice = await browser.newContext({ baseURL: 'http://127.0.0.1:4181', viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' })
  const otherAccount = await browser.newContext({ baseURL: 'http://127.0.0.1:4181', viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' })
  try {
    await prepare(otherDevice, 12)
    await prepare(otherAccount, 13)
    const second = await otherDevice.newPage()
    await open(second)
    await login(second, 'Alice')
    await progress(second)
    await expect(second.locator('.activity-history article')).toHaveCount(2)
    await expect(second.locator('.activity-history')).toContainText('23 min')
    const bob = await otherAccount.newPage()
    await open(bob)
    await login(bob, 'Bob')
    expect((await readState(bob)).data.progress.cardio).toEqual([])
    await progress(bob)
    await expect(bob.getByText('Tu primer paso todavía está por escribir.')).toBeVisible()
    const session = await page.evaluate(() => fetch('/api/auth/get-session').then(response => response.json()))
    const crossAccount = await bob.evaluate(async (aliceId: string) => {
      const result = await fetch('/api/me/state', { headers: { 'X-Klisteni-Account': aliceId } })
      return { status: result.status, cache: result.headers.get('cache-control') }
    }, session.user.id)
    expect(crossAccount).toEqual({ status: 401, cache: 'no-store' })
  } finally {
    await otherDevice.close()
    await otherAccount.close()
  }
  const panel = await accountPanel(page)
  await panel.getByRole('button', { name: 'Cerrar sesión', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Iniciar sesión', exact: true })).toBeVisible()
  await progress(page)
  await expect(page.locator('.activity-history article')).toHaveCount(1)
  await expect(page.locator('.activity-history')).toContainText('17 min')
  await expect(page.locator('.activity-history')).not.toContainText('23 min')
})

test('a failed network save survives reload and retries exactly once', async ({ page, context }) => {
  await prepare(context, 21)
  await open(page)
  await login(page, 'Offline')
  await page.route('**/api/me/logs', route => route.abort('internetdisconnected'))
  await saveCardio(page, 31)
  await expect(page.locator('.local-badge')).toContainText('1 envíos pendientes')
  const pendingKeys = () => page.evaluate(() => Object.keys(localStorage).filter(key => key.startsWith('klisteniapp.pending.v1.')))
  expect(await pendingKeys()).toHaveLength(1)
  expect((await readState(page)).data.progress.cardio).toEqual([])
  await page.reload()
  await expect(page.locator('.local-badge')).toContainText('1 envíos pendientes')
  await progress(page)
  await expect(page.locator('.activity-history article')).toHaveCount(1)
  await page.unroute('**/api/me/logs')
  await page.getByRole('button', { name: 'Reintentar sincronización', exact: true }).click()
  await expect(page.locator('.local-badge')).toContainText('Sincronizado con tu cuenta')
  expect(await pendingKeys()).toHaveLength(0)
  const state = await readState(page)
  expect(state.data.progress.cardio).toHaveLength(1)
  expect(state.data.progress.cardio[0].minutes).toBe(31)
  await page.reload()
  await progress(page)
  await expect(page.locator('.activity-history article')).toHaveCount(1)
  expect((await readState(page)).data.progress.cardio).toEqual(state.data.progress.cardio)
})

test('profile, routines and training days follow the account across device timezones', async ({ page, context, browser }, testInfo) => {
  await prepare(context, 31)
  const instant = new Date()
  instant.setUTCHours(23, 30, 0, 0)
  await page.clock.setFixedTime(instant)
  await open(page)
  await login(page, 'Planner')
  const panel = await accountPanel(page)
  await panel.getByLabel('Nombre', { exact: true }).fill('Mi práctica viajera')
  await panel.getByLabel('Zona horaria', { exact: true }).fill('Pacific/Kiritimati')
  await panel.getByLabel(/Guardar una copia de la rutina/).fill('Rutina de viaje')
  for (const day of ['Lunes', 'Miércoles', 'Viernes']) await panel.getByLabel(day, { exact: true }).uncheck()
  for (const day of ['Martes', 'Jueves']) await panel.getByLabel(day, { exact: true }).check()
  await panel.getByRole('button', { name: 'Guardar mi planificación' }).click()
  await expect.poll(async () => (await readState(page)).data.settings.profile.displayName).toBe('Mi práctica viajera')
  const state = await readState(page)
  expect(state.data.settings.plans[0].weekdays).toEqual([2, 4])
  expect(state.data.settings.routines.find(routine => routine.id === state.data.settings.activeRoutineId)?.name).toBe('Rutina de viaje')
  await expect(panel.getByLabel('Rutina activa')).toHaveValue(state.data.settings.activeRoutineId)
  await panel.evaluate(element => { element.scrollTop = 0 })
  await page.screenshot({ path: testInfo.outputPath('signed-in-account-planning.png') })
  await page.setViewportSize({ width: 390, height: 844 })
  const mobileWidth = await page.evaluate(() => ({ viewport: window.innerWidth, content: document.documentElement.scrollWidth }))
  expect(mobileWidth.content).toBeLessThanOrEqual(mobileWidth.viewport + 1)
  const bounds = await panel.boundingBox()
  expect(bounds).not.toBeNull()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(391)
  await panel.evaluate(element => { element.scrollTop = 0 })
  await page.screenshot({ path: testInfo.outputPath('signed-in-account-mobile.png') })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await panel.getByRole('button', { name: 'Cerrar', exact: true }).click()
  const expectedDate = dateInTimeZone(instant, 'Pacific/Kiritimati')
  await page.getByRole('button', { name: 'Registrar actividad', exact: true }).click()
  await expect(page.getByRole('dialog').getByLabel('¿Cuándo?')).toHaveValue(expectedDate)
  await page.getByRole('dialog').getByLabel('Duración (minutos)').fill('20')
  await page.getByRole('dialog').getByRole('button', { name: 'Guardar actividad', exact: true }).click()
  await expect.poll(async () => (await readState(page)).data.progress.cardio.length).toBe(1)
  expect((await readState(page)).data.progress.cardio[0]).toMatchObject({ date: expectedDate, timeZone: 'Pacific/Kiritimati' })
  const traveler = await browser.newContext({ baseURL: 'http://127.0.0.1:4181', timezoneId: 'Pacific/Honolulu', viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' })
  try {
    await prepare(traveler, 32)
    const second = await traveler.newPage()
    await second.clock.setFixedTime(instant)
    await open(second)
    await login(second, 'Planner')
    expect((await readState(second)).data.settings).toEqual(state.data.settings)
    expect((await readState(second)).data.progress.cardio[0]).toMatchObject({ date: expectedDate, timeZone: 'Pacific/Kiritimati' })
    const secondPanel = await accountPanel(second)
    await expect(secondPanel.getByLabel('Nombre', { exact: true })).toHaveValue('Mi práctica viajera')
    await expect(secondPanel.getByLabel('Martes', { exact: true })).toBeChecked()
    await expect(secondPanel.getByLabel('Jueves', { exact: true })).toBeChecked()
    await secondPanel.getByRole('button', { name: 'Cerrar', exact: true }).click()
    await second.getByRole('button', { name: 'Registrar actividad', exact: true }).click()
    await expect(second.getByRole('dialog').getByLabel('¿Cuándo?')).toHaveValue(expectedDate)
  } finally { await traveler.close() }
})

test('a full v2 copy restores historical plans into a pristine account and exports faithfully', async ({ page, context }) => {
  await prepare(context, 41)
  const data = createDefaultPersonalData('Cuenta recuperada', 'Europe/Paris')
  data.settings.routines[0].name = 'Rutina recuperada'
  data.settings.plans = [{ id: 'old-plan', effectiveFrom: '2026-01-05', weekdays: [1, 3, 5], routineId: 'starter' }]
  data.progress.cardio = [{ id: 'restored-log', date: '2026-09-29', activity: 'bike', minutes: 42 }]
  await open(page)
  await login(page, 'Restore')
  await page.getByRole('button', { name: 'Abrir ajustes', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.locator('input[type="file"]').setInputFiles({ name: 'personal-data-v2.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(data)) })
  await dialog.getByLabel('Restaurar también perfil, rutinas y planificación de una copia completa').check()
  await dialog.getByRole('button', { name: 'Incorporar historial', exact: true }).click()
  await expect(dialog).toContainText('Copia importada.')
  expect((await readState(page)).data).toEqual(data)
  const downloadPromise = page.waitForEvent('download')
  await dialog.getByRole('button', { name: 'Exportar progreso' }).click()
  const stream = await (await downloadPromise).createReadStream()
  if (!stream) throw new Error('Export did not produce a file')
  let exported = ''
  for await (const chunk of stream) exported += String(chunk)
  expect(JSON.parse(exported)).toEqual(data)
})

test('an administrator invites a member, the member activates and recovers without losing personal history', async ({ page, context, browser }) => {
  await prepare(context, 51)
  await open(page)
  await login(page, 'Admin')
  const panel = await accountPanel(page)
  await panel.getByText('Usuarios e invitaciones', { exact: true }).click()
  await panel.getByLabel('Email de la persona').fill('invited@accounts.test')
  await panel.locator('.admin-invite-form input[name="name"]').fill('Persona invitada')
  await panel.getByRole('button', { name: 'Crear invitación', exact: true }).click()
  await expect(panel.getByLabel('Enlace personal', { exact: true })).toHaveValue(/\/account\/activate#token=/)
  const activationUrl = await panel.getByLabel('Enlace personal', { exact: true }).inputValue()
  const memberContext = await browser.newContext({ baseURL: 'http://127.0.0.1:4181', viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' })
  await prepare(memberContext, 52)
  try {
    const member = await memberContext.newPage()
    await member.goto(activationUrl)
    await expect(member).toHaveURL(/\/account\/activate$/)
    await expect(member.getByLabel('Email de la invitación')).toHaveValue('invited@accounts.test')
    await member.getByLabel('Tu nombre', { exact: true }).fill('Persona invitada')
    await member.getByLabel('Elegí una contraseña', { exact: true }).fill(password)
    await member.getByLabel('Repetí la contraseña', { exact: true }).fill(password)
    await member.getByRole('button', { name: 'Activar mi cuenta', exact: true }).click()
    await expect(member.getByRole('heading', { name: 'Tu cuenta está lista.' })).toBeVisible()
    await member.getByRole('link', { name: 'Iniciar sesión', exact: true }).click()
    const loginPanel = member.getByRole('dialog', { name: 'Entrar a Klisteni' })
    await loginPanel.getByLabel('Email', { exact: true }).fill('invited@accounts.test')
    await loginPanel.getByLabel('Contraseña', { exact: true }).fill(password)
    await loginPanel.getByRole('button', { name: 'Entrar a mi cuenta' }).click()
    await expect(loginPanel).not.toBeVisible()
    await saveCardio(member, 19)
    expect((await readState(member)).data.progress.cardio[0].minutes).toBe(19)
    const memberPanel = await accountPanel(member)
    await expect(memberPanel.getByText('Usuarios e invitaciones', { exact: true })).toHaveCount(0)
    await memberPanel.getByRole('button', { name: 'Cerrar', exact: true }).click()
    await panel.getByRole('button', { name: 'Actualizar', exact: true }).click()
    // Users and consumed invitations both contain the email; only the user row offers recovery.
    const userRow = panel.locator('.admin-row').filter({ has: page.getByRole('button', { name: 'Crear recuperación', exact: true }) }).filter({ hasText: 'invited@accounts.test' })
    await expect(userRow).toHaveCount(1)
    await userRow.getByRole('button', { name: 'Crear recuperación', exact: true }).click()
    await expect(panel.getByLabel('Enlace personal', { exact: true })).toHaveValue(/\/account\/recover#token=/)
    const recoveryUrl = await panel.getByLabel('Enlace personal', { exact: true }).inputValue()
    await member.goto(recoveryUrl)
    await expect(member).toHaveURL(/\/account\/recover$/)
    const replacement = 'Recovered-account-password-2026!'
    await member.getByLabel('Nueva contraseña', { exact: true }).fill(replacement)
    await member.getByLabel('Repetí la contraseña', { exact: true }).fill(replacement)
    await member.getByRole('button', { name: 'Guardar nueva contraseña' }).click()
    await expect(member.getByRole('heading', { name: 'Contraseña actualizada.' })).toBeVisible()
    expect(await member.evaluate(() => fetch('/api/auth/get-session', { cache: 'no-store' }).then(response => response.json()))).toBeNull()
    await member.getByRole('link', { name: 'Iniciar sesión', exact: true }).click()
    const recoveredLogin = member.getByRole('dialog', { name: 'Entrar a Klisteni' })
    await recoveredLogin.getByLabel('Email', { exact: true }).fill('invited@accounts.test')
    await recoveredLogin.getByLabel('Contraseña', { exact: true }).fill(replacement)
    await recoveredLogin.getByRole('button', { name: 'Entrar a mi cuenta' }).click()
    await expect(recoveredLogin).not.toBeVisible()
    expect((await readState(member)).data.progress.cardio[0].minutes).toBe(19)
    await panel.getByRole('button', { name: 'Actualizar', exact: true }).click()
    await userRow.getByRole('button', { name: 'Deshabilitar acceso', exact: true }).click()
    await expect(panel.locator('.admin-row').filter({ hasText: 'invited@accounts.test' }).filter({ hasText: 'Deshabilitado' })).toBeVisible()
    expect(await member.evaluate(() => fetch('/api/auth/get-session', { cache: 'no-store' }).then(response => response.json()))).toBeNull()
  } finally { await memberContext.close() }
})
