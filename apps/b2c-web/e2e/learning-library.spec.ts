import { expect, test } from '@playwright/test'

test.use({ reducedMotion: 'reduce' })
test.beforeEach(async ({ page }) => {
  await page.route('**/models/*.glb', route => route.abort())
  await page.setViewportSize({ width: 390, height: 844 })
})

test('encyclopedia searches anatomy and yoga and opens existing guidance without creating activity', async ({ page }) => {
  await page.goto('/')
  const before = await page.evaluate(() => ({ personal: localStorage.getItem('klisteniapp.personal.v2'), progress: localStorage.getItem('klisteniapp.progress.v1') }))
  await page.getByRole('navigation', { name: 'Navegación móvil', exact: true }).getByRole('button', { name: 'Mi cuerpo', exact: true }).click()
  const search = page.getByRole('searchbox', { name: 'Buscar anatomía o yoga', exact: true })
  await search.fill('supinacion')
  await expect(page.locator('.body-muscle')).toHaveCount(1)
  await expect(page.locator('.body-muscle summary')).toContainText('Bíceps')
  await search.fill('tree pose')
  await expect(page.locator('.body-muscle')).toHaveCount(0)
  const yoga = page.getByRole('region', { name: 'Yoga en la enciclopedia', exact: true })
  await expect(yoga.getByRole('button')).toHaveCount(1)
  await yoga.getByRole('button').click()
  const dialog = page.getByRole('dialog', { name: 'Árbol', exact: true })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('heading', { name: 'Cuidados para esta asana', exact: true })).toBeVisible()
  await expect(dialog.getByRole('heading', { name: 'Fuentes y lecturas', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  const after = await page.evaluate(() => ({ personal: localStorage.getItem('klisteniapp.personal.v2'), progress: localStorage.getItem('klisteniapp.progress.v1') }))
  expect(after).toEqual(before)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('exercise offers optional regional stretching references and retains the selected routine', async ({ page }) => {
  await page.goto('/')
  const routine = await page.evaluate(() => localStorage.getItem('klisteniapp.preferences.v1'))
  const mobility = page.locator('.workbench .contextual-mobility')
  await mobility.locator('summary').click()
  await expect(mobility).toContainText('no se agregan a tu rutina')
  await mobility.getByRole('button', { name: /Pierna elevada con apoyo/ }).click()
  const dialog = page.getByRole('dialog', { name: 'Pierna elevada con apoyo', exact: true })
  await expect(dialog).toBeVisible()
  await expect(dialog).toContainText('El lado indica la pierna elevada.')
  await page.keyboard.press('Escape')
  await page.getByRole('navigation', { name: 'Navegación móvil', exact: true }).getByRole('button', { name: 'Mi rutina', exact: true }).click()
  await expect(page.locator('.workbench-title')).toContainText('Sentadilla')
  expect(await page.evaluate(() => localStorage.getItem('klisteniapp.preferences.v1'))).toBe(routine)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
