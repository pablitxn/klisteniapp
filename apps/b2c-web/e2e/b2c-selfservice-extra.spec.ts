import { expect, test, type Page } from '@playwright/test'
import type { ServerState } from '@klisteniapp/scene-schema'
import { openSettings } from './settings-helpers'
const nav = (page: Page, name: string) => page.getByRole('navigation', { name: /Navegación (principal|móvil)/ }).getByRole('button', { name, exact: true }).click()
async function login(page: Page, name: string) {
  await page.goto('/?account=login')
  await page.getByLabel('Email', { exact: true }).fill(`${name.toLowerCase()}@accounts.test`)
  await page.getByLabel('Contraseña', { exact: true }).fill('Only-for-browser-tests-2026!')
  await page.getByRole('button', { name: 'Entrar a mi cuenta' }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
}
async function state(page: Page): Promise<ServerState> {
  return page.evaluate(async () => {
    const session = await fetch('/api/auth/get-session').then(r => r.json())
    const response = await fetch('/api/me/state', { headers: { 'X-Klisteni-Account': session.user.id } })
    if (!response.ok) throw new Error(`State ${response.status}`)
    return response.json()
  })
}
async function width(page: Page) { expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1) }
const errors = new WeakMap<Page, string[]>()
const abortedAssets = new WeakMap<Page, Set<string>>()
test.beforeEach(async ({ page, context }, info) => {
  await context.setExtraHTTPHeaders({ 'X-Klisteniapp-Test-Client-IP': `203.0.113.${100 + info.line % 100}` })
  abortedAssets.set(page, new Set())
  await context.route('**/models/*.glb', r => { abortedAssets.get(page)!.add(new URL(r.request().url()).pathname); return r.abort() })
  errors.set(page, [])
  page.on('pageerror', error => errors.get(page)!.push(error.message))
})
test.afterEach(async ({ page }, info) => {
  await info.attach('uncaught-ui-errors', { contentType: 'application/json', body: JSON.stringify(errors.get(page)) })
  const unexpected = errors.get(page)!.filter(message => ![...abortedAssets.get(page)!].some(path => [ `Could not load ${path}: Failed to fetch`, `Could not load ${path}: Load failed` ].includes(message)))
  await info.attach('unexpected-ui-errors', { contentType: 'application/json', body: JSON.stringify(unexpected) })
  expect(unexpected).toEqual([])
})

